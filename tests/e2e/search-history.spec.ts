import { test, expect } from '@playwright/test'

const backend = 'http://127.0.0.1:5174'
const guestHistoryKey = 'rezka.search-history.https%3A%2F%2Fhdrezka-home.tv.guest'
test.beforeEach(async ({ request }) => { await request.post(backend + '/api/test/reset') })

test('submitted searches persist uniquely and can be run again from Search', async ({ page }) => {
  const calls: string[] = []
  await page.route('**/api/rpc', async route => {
    const body = route.request().postDataJSON()
    if (body.method === 'search') calls.push(body.params.query)
    await route.fallback()
  })
  await page.goto('/'); await page.locator('[data-nav-id="nav-search"]').click()
  const input = page.getByLabel('Название фильма или сериала')
  await input.fill('авто')
  await expect.poll(() => calls).toContain('авто')
  expect(await page.evaluate(key => localStorage.getItem(key), guestHistoryKey)).toBeNull()
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key) || '[]'), guestHistoryKey)).toEqual(['авто'])
  await input.fill('дюна'); await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await input.fill('авто'); await page.getByRole('button', { name: 'Найти', exact: true }).click()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key) || '[]'), guestHistoryKey)).toEqual(['авто', 'дюна'])

  await page.reload(); await page.locator('[data-nav-id="nav-search"]').click()
  const history = page.getByRole('region', { name: 'Недавние запросы' })
  await expect(history.locator('.search-history-query')).toHaveText(['авто', 'дюна'])
  await history.getByRole('button', { name: 'дюна', exact: true }).click()
  await expect(input).toHaveValue('дюна')
  await expect.poll(() => calls.filter(query => query === 'дюна').length).toBeGreaterThanOrEqual(2)
  await history.getByRole('button', { name: 'Очистить', exact: true }).click()
  await expect(history).toHaveCount(0)
  await expect(input).toBeFocused()
  expect(await page.evaluate(key => localStorage.getItem(key), guestHistoryKey)).toBeNull()
})

