test('guest and account search histories stay isolated on a shared TV', async ({ page }) => {
  await page.goto('/'); await page.locator('[data-nav-id="nav-search"]').click()
  const input = page.getByLabel('Название фильма или сериала')
  await input.fill('гостевой запрос'); await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await page.locator('[data-nav-id="nav-profile"]').click()
  await page.getByLabel('Логин или e-mail').fill('demo@example.test')
  await page.getByLabel('Пароль', { exact: true }).fill('demo-only')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.locator('[data-nav-id="nav-search"]').click()
  await expect(page.getByRole('region', { name: 'Недавние запросы' })).toHaveCount(0)
  await input.fill('запрос аккаунта'); await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await page.locator('[data-nav-id="nav-profile"]').click(); await page.getByRole('button', { name: 'Выйти из аккаунта', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Выйти', exact: true }).click()
  await page.locator('[data-nav-id="nav-search"]').click()
  await expect(page.getByRole('region', { name: 'Недавние запросы' }).locator('.search-history-query')).toHaveText(['гостевой запрос'])
})

test('D-pad reaches Find and Clear without reopening the search input', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, JSON.stringify(['дюна', 'аватар'])), guestHistoryKey)
  await page.goto('/'); await page.locator('[data-nav-id="nav-search"]').click()
  const input = page.getByLabel('Название фильма или сериала')
  const find = page.getByRole('button', { name: 'Найти', exact: true })
  const clear = page.getByRole('button', { name: 'Очистить', exact: true })
  const queries = page.getByRole('region', { name: 'Недавние запросы' }).locator('.search-history-query')
  await expect(input).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(queries.first()).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(find).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(queries.first()).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(queries.nth(1)).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(clear).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(find).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(input).toBeFocused()
})

test('Right leaves the search field only when the caret reaches the end', async ({ page }) => {
  await page.goto('/'); await page.locator('[data-nav-id="nav-search"]').click()
  const input = page.getByLabel('Название фильма или сериала')
  await input.fill('гладиатор')
  await input.evaluate((element: HTMLInputElement) => element.setSelectionRange(3, 3))
  await page.keyboard.press('ArrowRight')
  await expect(input).toBeFocused()
  expect(await input.evaluate((element: HTMLInputElement) => element.selectionStart)).toBe(4)
  await input.evaluate((element: HTMLInputElement) => element.setSelectionRange(element.value.length, element.value.length))
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: 'Найти', exact: true })).toBeFocused()
})

