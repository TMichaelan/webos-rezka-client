test('holding Down advances one player zone and blur clears the latch', async ({ page }) => {
  await openPausedPlayer(page)
  const stage = page.locator('.player-stage')
  const range = page.getByRole('slider', { name: 'Позиция видео' })
  await stage.focus()
  for (let index = 0; index < 6; index++) {
    await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', keyCode: 40, repeat: false, bubbles: true, cancelable: true })))
    await page.waitForTimeout(50)
  }
  await expect(range).toBeFocused()
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: 'Воспроизвести', exact: true })).toBeFocused()
})

test('previous and next episode actions are ordered left of playback settings', async ({ page }) => {
  await openPausedPlayer(page, 2)
  const row = page.locator('.control-row')
  await expect(row.locator('.episode-actions').getByRole('button')).toHaveCount(3)
  await expect(row.locator('.episode-actions').getByRole('button').nth(0)).toHaveAttribute('aria-label', 'Предыдущая серия')
  await expect(row.locator('.episode-actions').getByRole('button').nth(1)).toHaveAttribute('aria-label', 'Воспроизвести')
  await expect(row.locator('.episode-actions').getByRole('button').nth(2)).toHaveAttribute('aria-label', 'Следующая серия')
  await expect(row.locator('.playback-actions').getByRole('combobox')).toHaveCount(2)
  await expect(row.locator('.playback-actions').getByRole('button', { name: 'Формат экрана', exact: true })).toBeVisible()
  const previousBox = await page.getByRole('button', { name: 'Предыдущая серия', exact: true }).boundingBox()
  const qualityBox = await page.getByRole('combobox', { name: 'Качество', exact: true }).boundingBox()
  expect(previousBox!.x).toBeLessThan(qualityBox!.x)
  await page.getByRole('button', { name: 'Предыдущая серия', exact: true }).click()
  await expect(page.locator('.player-heading')).toContainText('Серия 1')
  await expect(page.getByRole('button', { name: 'Предыдущая серия', exact: true })).toHaveCount(0)
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  await expect(page.locator('.player-skeleton')).toHaveCount(0)
  await page.getByRole('button', { name: 'Следующая серия', exact: true }).click()
  await expect(page.locator('.player-heading')).toContainText('Серия 2')
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  await page.locator('.player-stage').focus(); await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
  await expect(page.locator('[data-nav-id="episode-1-2"]')).toHaveAttribute('aria-pressed', 'true')
})

test('direct icon quality shows actual selected resolution and one check, without max or extra player selectors', async ({ page }) => {
  await openPausedPlayer(page)
  const quality = page.locator('.player').getByRole('combobox', { name: 'Качество', exact: true })
  await expect(quality).toHaveAttribute('data-value', '720p')
  await expect(quality.locator('svg')).toHaveCount(1)
  await expect(quality).toHaveText('')
  const subtitles = page.locator('.player').getByRole('combobox', { name: 'Субтитры', exact: true })
  await expect(subtitles.locator('svg')).toHaveCount(1)
  await expect(subtitles).toHaveAttribute('data-value', '')
  await expect(page.locator('.player').getByRole('combobox')).toHaveCount(2)
  await quality.click()
  await expect(page.getByRole('option').and(page.locator('[data-value="max"]'))).toHaveCount(0)
  const selected = page.getByRole('option', { selected: true })
  await expect(selected).toHaveCount(1)
  await expect(selected).toHaveAttribute('data-value', '720p')
  await expect(selected.locator('[aria-hidden="true"]')).toHaveText('✓')
  await page.keyboard.press('Escape'); await expect(quality).toBeFocused()
})
