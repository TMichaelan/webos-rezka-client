import { test, expect, type Page } from '@playwright/test'

async function openPausedPlayer(page: Page, selectedEpisode = 1) {
  await page.route('**/api/rpc', async route => {
    if (route.request().postDataJSON().method === 'progress') await route.fulfill({ json: { returnValue: true, result: null } })
    else await route.continue()
  })
  await page.goto('/')
  await page.locator('[data-nav-id="nav-profile"]').click()
  await expect(page.getByLabel('Логин или e-mail')).toBeFocused()
  await page.getByLabel('Логин или e-mail').fill('demo@example.test')
  await page.getByLabel('Пароль', { exact: true }).fill('demo-only')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Выйти из аккаунта', exact: true })).toBeVisible()
  await page.locator('[data-nav-id="nav-home"]').click()
  await page.locator('[data-nav-id="continue-100"]').click()
  if (selectedEpisode !== 1) await page.locator(`[data-nav-id="episode-1-${selectedEpisode}"]`).click()
  await page.locator('[data-nav-id="detail-play"]').click()
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).paused)).toBe(false)
  await page.locator('video').evaluate(v => { const video = v as HTMLVideoElement; video.pause(); video.currentTime = 30 })
  await expect(page.getByRole('slider', { name: 'Позиция видео' })).toHaveValue('30')
}
test.beforeEach(async ({ request }) => { await request.post('http://127.0.0.1:5174/api/test/reset') })

test('Back needs two distinct presses to leave active playback', async ({ page }) => {
  await openPausedPlayer(page)
  await page.locator('.player-stage').focus()
  await page.evaluate(() => {
    const event = () => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }))
    event(); event()
  })
  await expect(page.locator('video')).toHaveCount(1)
  await expect(page.locator('.player-back-hint')).toContainText('Нажмите Back ещё раз')
  await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keyup', { key: 'Escape', bubbles: true })))
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('.player-back-hint')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.locator('video')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await expect(page.locator('video')).toHaveCount(0)
})

test('horizontal seek focuses timeline then play/pause; two Down presses hide controls', async ({ page }) => {
  await openPausedPlayer(page)
  const stage = page.locator('.player-stage')
  const range = page.getByRole('slider', { name: 'Позиция видео' })
  const toggle = page.getByRole('button', { name: 'Воспроизвести', exact: true })
  await stage.focus(); await page.keyboard.press('ArrowRight')
  await expect(range).toBeFocused()
  await expect(range).toHaveValue('40')
  await page.keyboard.press('ArrowDown'); await expect(toggle).toBeFocused()
  await page.keyboard.press('ArrowDown'); await expect(stage).toBeFocused()
  await expect(page.locator('.player-overlay')).toHaveClass(/controls-hidden/)
  await page.keyboard.press('ArrowUp'); await expect(toggle).toBeFocused()
  await page.keyboard.press('ArrowUp'); await expect(range).toBeFocused()
  await page.keyboard.press('ArrowUp'); await expect(stage).toBeFocused()
  await expect(page.locator('.player-overlay')).toHaveClass(/controls-hidden/)
  await page.keyboard.press('ArrowDown'); await expect(range).toBeFocused()
  expect(await page.locator('video').evaluate(v => (v as HTMLVideoElement).currentTime)).toBe(40)
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).paused)).toBe(false)
  await expect(page.getByRole('button', { name: 'Пауза', exact: true })).toBeFocused()
  await expect(page.locator('video')).toBeVisible()
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape'); await expect(page.locator('video')).toHaveCount(0)
})

